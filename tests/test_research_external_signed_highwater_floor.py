def test_changed_local_anchor_between_readback_passes_no_go(lab, monkeypatch):
    lab["crash"]("source_after_commit_before_anchor")
    classifier = witness._classifier()
    original = classifier._read_snapshot
    calls = 0

    def change_after_first(*args):
        nonlocal calls
        first = original(*args)
        calls += 1
        if calls == 1:
            with sqlite3.connect(lab["anchor"]) as admin:
                admin.execute("UPDATE highwater SET commit_seq=13")
        return first

    monkeypatch.setattr(classifier, "_read_snapshot", change_after_first)
    result = lab["assess"](lab["sign"](11))
    assert calls == 2
    assert result["verdict"] == "CHANGED_BETWEEN_READBACKS_NO_GO"


