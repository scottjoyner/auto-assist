def test_external_witness_does_not_attempt_local_rollback_repair(lab, tmp_path):
    snapshot = tmp_path / "saved-old.sqlite"
    shutil.copy2(lab["anchor"], snapshot)
    lab["crash"]("no_crash")
    shutil.copy2(snapshot, lab["anchor"])
    before = lab["anchor"].read_bytes()
    result = lab["assess"](lab["sign"](12))
    assert result["verdict"] == "EXTERNAL_WITNESS_DETECTS_ANCHOR_RESTORE_NO_GO"
    assert lab["anchor"].read_bytes() == before
    assert result["retry_authorized"] is False
