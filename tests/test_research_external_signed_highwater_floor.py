from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/research-external-signed-highwater-floor.py"
SPEC = importlib.util.spec_from_file_location("test_external_floor", SCRIPT)
assert SPEC and SPEC.loader
witness = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(witness)
CRASH = ROOT / "tests/test_research_receipt_subprocess_crash_matrix.py"
C_SPEC = importlib.util.spec_from_file_location("test_crash_for_witness", CRASH)
assert C_SPEC and C_SPEC.loader
crash = importlib.util.module_from_spec(C_SPEC)
C_SPEC.loader.exec_module(crash)
TERMINAL = ROOT / "tests/test_research_terminal_receipt_readback.py"
